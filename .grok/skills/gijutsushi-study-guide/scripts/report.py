#!/usr/bin/env python3
"""Coverage and priority report for planning the study guide (run after extract.py).

Writes artifacts/coverage_report.md with:
  1. miss rate per exam block (Q1-7 有機, Q8-14 燃料, Q15-21 高分子, Q22-28 無機, Q29-35 計算)
  2. item priority ranking: score = years cited + 2 if ever missed (ties: more questions first)
  3. gap scan: hit counts for each topic regex in assets/gap_keywords.tsv; <= --gap-threshold hits is a gap
The report is regenerated each run; use it to update content/outline.md.
"""
from __future__ import annotations

import argparse
import csv
import re
import sys
from collections import Counter
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent
ROOT = Path(__file__).resolve().parents[4]
BLOCKS = [(1, 7, "有機化学"), (8, 14, "燃料・エネルギー"), (15, 21, "高分子"), (22, 28, "無機・セラミックス"), (29, 35, "計算")]
BAD = {"wrong", "guessed", "missed_log"}


def read_csv(path: Path) -> list[dict]:
    with open(path, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def block_of(qid: str) -> str | None:
    m = re.search(r"-Q(\d+)$", qid)
    if not m:
        return None
    n = int(m.group(1))
    return next((name for lo, hi, name in BLOCKS if lo <= n <= hi), None)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--repo", type=Path, default=ROOT, help="repository root (default: derived from script location)")
    p.add_argument("--keywords", type=Path, default=SKILL / "assets" / "gap_keywords.tsv", help="label<TAB>regex file")
    p.add_argument("--gap-threshold", type=int, default=5, help="hit count at or below which a topic is a gap")
    p.add_argument("--top", type=int, default=60, help="number of ranked items to list")
    a = p.parse_args()

    ex = a.repo / "extracted"
    if not (ex / "index_items.csv").is_file():
        print(f"error: {ex / 'index_items.csv'} missing; run extract.py first", file=sys.stderr)
        return 1
    items, qs = read_csv(ex / "index_items.csv"), read_csv(ex / "index_questions.csv")

    lines = ["# Coverage and priority report", "", "Generated by report.py. Do not edit.", "",
             "## 1. Miss rate per block (questions with a recorded result)", "",
             "| Block | Known | Wrong/guessed | Miss rate | Partly right |", "|---|---|---|---|---|"]
    known, bad, part = Counter(), Counter(), Counter()
    for q in qs:
        b = block_of(q["qid"])
        if not b or q["status"] == "unknown":
            continue
        known[b] += 1
        bad[b] += q["status"] in BAD
        part[b] += q["status"] == "right_partial"
    for _, _, b in BLOCKS:
        rate = f"{bad[b] / known[b]:.0%}" if known[b] else "n/a"
        lines.append(f"| {b} | {known[b]} | {bad[b]} | {rate} | {part[b]} |")

    def score(r):
        return int(r["n_years"]) + (2 if r["missed"] else 0), int(r["n_questions"])

    ranked = sorted(items, key=score, reverse=True)
    lines += ["", f"## 2. Item priority (top {a.top})", "", "| Item | Score | Years | Missed in | Title |", "|---|---|---|---|---|"]
    for r in ranked[: a.top]:
        lines.append(f"| {r['id']} | {score(r)[0]} | {r['years']} | {r['missed']} | {r['title']} |")
    uncited = [r["id"] for r in items if r["n_questions"] == "0"]
    lines += ["", f"Items not linked to any question ({len(uncited)}): {' '.join(uncited)}"]

    corpus = "\n".join(f.read_text(encoding="utf-8") for d in ("items", "questions") for f in sorted((ex / d).glob("*.md")))
    lines += ["", f"## 3. Gap scan (gap = at most {a.gap_threshold} hits)", "", "| Topic | Hits | Gap |", "|---|---|---|"]
    for raw in a.keywords.read_text(encoding="utf-8").splitlines():
        if not raw.strip() or raw.startswith("#"):
            continue
        label, _, rx = raw.partition("\t")
        n = len(re.findall(rx, corpus))
        lines.append(f"| {label} | {n} | {'GAP' if n <= a.gap_threshold else ''} |")

    out = a.repo / "artifacts" / "coverage_report.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
