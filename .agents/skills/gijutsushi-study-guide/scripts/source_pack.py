#!/usr/bin/env python3
"""Assemble the source material for one chapter into a single Markdown pack for writing.

Reads the chapter's section table in content/outline.md (rows "| 1.2 | topic | items | pages |"),
collects every item id (F##, S###, T###) with its treatment mark (★ ● ・), and appends:
  - the full text of each item from extracted/items/
  - for the chapter's exam block: every question's title/status and its key lines
    (一句速記, 陷阱, 重點, 修正, 正答…為何錯) from extracted/questions/
  - the block's 失點紀錄 rows from extracted/misses.csv
Writes artifacts/packs/chapter<N>.md (regenerated each run).
"""
from __future__ import annotations

import argparse
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
BLOCKS = {1: (1, 7), 2: (15, 21), 3: (8, 14), 4: (22, 28), 5: (29, 35)}
KEY = re.compile(r"^(一句速記|陷阱|重點|重点|修正|正答|正解為何|快解|重複|錯因|考點)")
ID = re.compile(r"\b([FST]\d{2,3})([★●・])?")


def chapter_rows(outline: str, chapter: int) -> list[tuple[str, str, list[tuple[str, str]], str]]:
    m = re.search(rf"^## {chapter}\. .*?$(.*?)(?=^## )", outline, re.M | re.S)
    if not m:
        sys.exit(f"error: chapter {chapter} not found in outline")
    rows = []
    for line in m.group(1).splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 4 and re.match(rf"{chapter}\.\d", cells[0]):
            ids = [(i, mark or "") for i, mark in ID.findall(cells[2])]
            rows.append((cells[0], cells[1], ids, cells[3]))
    return rows


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("chapter", type=int, help="chapter number in content/outline.md (1-5)")
    p.add_argument("--repo", type=Path, default=ROOT, help="repository root (default: derived from script location)")
    p.add_argument("--no-questions", action="store_true", help="omit the per-question key lines")
    a = p.parse_args()

    ex = a.repo / "extracted"
    rows = chapter_rows((a.repo / "content" / "outline.md").read_text(encoding="utf-8"), a.chapter)
    out = [f"# Source pack: chapter {a.chapter}", "", "Generated by source_pack.py. Do not edit.", ""]
    for sec, topic, ids, pages in rows:
        out += [f"## § {sec} {topic} (budget {pages} p)", ""]
        for iid, mark in ids:
            f = ex / "items" / f"{iid}.md"
            if not f.is_file():
                out += [f"### {iid} — MISSING", ""]
                continue
            body = f.read_text(encoding="utf-8").splitlines()
            out += [f"### [{mark or '?'}] {body[0].lstrip('# ')}", ""] + body[1:] + [""]

    if a.chapter in BLOCKS and not a.no_questions:
        lo, hi = BLOCKS[a.chapter]
        with open(ex / "index_questions.csv", encoding="utf-8-sig", newline="") as f:
            qs = [r for r in csv.DictReader(f) if (m := re.search(r"-Q(\d+)$", r["qid"])) and lo <= int(m.group(1)) <= hi]
        out += [f"## Past questions Q{lo}–Q{hi} ({len(qs)}) — key lines", ""]
        for r in qs:
            text = (ex / "questions" / f"{r['qid']}.md").read_text(encoding="utf-8").splitlines()
            keys = [l for l in text if KEY.match(l)]
            out += [f"### {r['qid']} [{r['status']}] {r['title']}  (refs: {r['refs']})"] + keys + [""]
        with open(ex / "misses.csv", encoding="utf-8-sig", newline="") as f:
            ms = [r for r in csv.DictReader(f) if lo <= int(r["qid"].rsplit("Q", 1)[1]) <= hi]
        out += [f"## 失點紀錄 rows ({len(ms)})", "", "| Q | 類型 | 對策 |", "|---|---|---|"]
        out += [f"| {r['qid']} | {r['type']} | {r['fix']} |" for r in ms]

    dst = a.repo / "artifacts" / "packs" / f"chapter{a.chapter}.md"
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {dst} ({len(rows)} sections, {sum(len(r[2]) for r in rows)} items, {dst.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
