#!/usr/bin/env python3
"""Generate the past-question index chapter (content/98_qindex.md) from extracted/index_questions.csv.

One section per exam block; rows sorted by question number then year, so the topic that recurs in
the same slot (e.g. 問9 = 石油製品) lines up. Result marks: ◯ right, △ partly right, ✗ wrong /
guessed / in a 失點紀錄, blank = no record. The file is regenerated each run; do not hand-edit it.
"""
from __future__ import annotations

import argparse
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
BLOCKS = [(1, 7, "有機化学", "第1章"), (8, 14, "燃料・エネルギー", "第3章"), (15, 21, "高分子", "第2章"),
          (22, 28, "無機・セラミックス・電気化学", "第4章"), (29, 35, "化学工学・物理化学（計算）", "第5章")]
MARK = {"right": "◯", "right_partial": "△", "wrong": "✗", "guessed": "✗", "missed_log": "✗"}
YEAR_ORDER = ["H23", "H24", "H25", "H26", "H27", "H28", "H29", "H30", "R1再", "R2", "R3", "R4", "R5", "R6", "R7"]


def clean_title(t: str, limit: int) -> str:
    t = re.sub(r"^(H\d{2}|R\d再?)-Q\d+\s*", "", t).replace("|", "｜").strip()
    t = re.sub(r"\s+", " ", t)
    return t if len(t) <= limit else t[: limit - 1] + "…"


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--repo", type=Path, default=ROOT, help="repository root (default: derived from script location)")
    p.add_argument("--max-title", type=int, default=34, help="truncate topic titles to this many characters")
    p.add_argument("--chunk", type=int, default=24, help="rows per table (tables cannot break across columns)")
    a = p.parse_args()
    src = a.repo / "extracted" / "index_questions.csv"
    if not src.is_file():
        print(f"error: {src} missing; run extract.py first", file=sys.stderr)
        return 1
    with open(src, encoding="utf-8-sig", newline="") as f:
        rows = [r for r in csv.DictReader(f) if r["year"] in YEAR_ORDER]

    out = ["<!-- Generated by qindex.py from extracted/index_questions.csv. Do not edit; re-run the script. -->",
           "<!-- label: 索引 -->", "",
           "# 過去問索引 H23〜R7 | 同じ題號は毎年ほぼ同じ分野", "",
           "> [!memo] 使い方",
           "> 題號順に並べてあるので、毎年同じ位置に出る分野（例：問9＝石油製品、問13＝石炭、問35＝計算）が縦に揃う。"
           "結果欄：◯＝答對、△＝部分正確、✗＝失分（本書の該当章の陷阱ボックスで復習）、空欄＝記録なし（H23〜H30 の多く）。", ""]
    total = 0
    for lo, hi, name, chap in BLOCKS:
        sel = [r for r in rows if lo <= int(r["qid"].rsplit("Q", 1)[1]) <= hi]
        sel.sort(key=lambda r: (int(r["qid"].rsplit("Q", 1)[1]), YEAR_ORDER.index(r["year"])))
        missed = sum(1 for r in sel if MARK.get(r["status"]) == "✗")
        out += [f"## 問{lo}〜問{hi} {name}（{chap}・{len(sel)} 題・失分 {missed}）", ""]
        for start in range(0, len(sel), a.chunk):
            out += ["<!-- cols: l X c -->", "| 題 | 主題 | 結果 |", "|---|---|---|"]
            out += [f"| {r['year']}-{r['qid'].rsplit('-', 1)[1]} | {clean_title(r['title'], a.max_title)} | "
                    f"{MARK.get(r['status'], '')} |" for r in sel[start:start + a.chunk]]
            out.append("")
        total += len(sel)
    dst = a.repo / "content" / "98_qindex.md"
    dst.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {dst} ({total} questions)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
